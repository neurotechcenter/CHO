function param = cho_v27_parameters()
%CHO_V27_PARAMETERS Explicit v27 preset used in the UAB research analyses.
% The detector itself defaults to frequency-dependent wavelet cycles and
% correlation merging. This preset explicitly selects fixed 8-cycle
% wavelets and fast time-frequency overlap merging instead.
param = struct('plot', 0, 'minimum_cycles', 3, ...
    'ovlp_threshold', 0.5, 'frequency_range', 1:150, ...
    'frequency_step', 1, 'wavelet_cycles', 8, ...
    'osc_threshold_std', 2, 'merge_mode', 'fast_tf_overlap', ...
    'fast_merge_time_overlap_frac', 0.05, 'fast_merge_freq_gap_hz', 1, ...
    'birdsong_tfmap', 0, 'plot_birdsong', 0);
end
